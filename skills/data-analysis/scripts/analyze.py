"""수집한 원본에서 「오늘 먼저 볼 것」을 골라 판정 JSON을 만든다.

**이 파일이 숫자에 대한 유일한 권한을 가진다.** 렌더러(HTML 카드·텍스트 보고)는
여기서 나온 JSON만 읽고 계산하지 않는다. LLM도 마찬가지다 —
Solar 는 문장을 다듬을 뿐 숫자를 만들거나 바꾸지 못한다(Scaffolding S2).

판정 방법 — **임의 임계치를 쓰지 않는다**

    기준가   같은 품목·같은 구분·같은 등급·**같은 달**의 과거 N년 월평균
    이상도   올해 값이 그 관측들 사이에서 **몇 번째로 높은가**
    순위     이상도가 큰 순

    「1.5배 넘으면 이상」 같은 우리가 고른 선이 없다. 비교 대상은 전부
    API 가 준 과거 관측이고, 판정은 그 관측들 사이의 **순위**다.
    이것이 Step 4 통과 기준(「임의 임계치가 하나도 없음」)을 만족시키는 방법이다.
"""
from __future__ import annotations

import json
import statistics
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone, timedelta

SCHEMA_VERSION = "1.0"
KST = timezone(timedelta(hours=9))


# ── 판정 결과 ────────────────────────────────────────────────────────
@dataclass
class 단계판정:
    """유통 한 단계에서 관측된 것. 원인이 아니라 **관측**이다."""
    단계: str                    # 산지 · 도매 · 소매
    단위: str                    # 🔴 단계마다 다르다. 붙이지 않으면 오독한다
    올해: float | None
    평년평균: float | None
    배수: float | None
    순위: str | None             # "1/6" — 과거 포함 몇 개 중 몇 번째
    관측: str                    # 화면 표시용 (자리 + 대비를 합친 말)
    자리: str = ""               # 순위 축 — "6년 중 3번째"
    대비: str = ""               # 평균 축 — "평년보다 높음" · "평년 수준" · "평년보다 낮음"


@dataclass
class 품목판정:
    순위: int
    품목: str
    구분: str                    # 소매 · 중도매
    등급: str
    올해: float
    평년평균: float
    배수: float
    순위표기: str                # "1/6"
    사람말: str                  # 통계 용어를 쓰지 않은 한 문장
    시계열: list[dict] = field(default_factory=list)   # [{"ym","값"}] 그래프용
    최고: dict | None = None      # 가장 크게 오른 한 곳
    그린구간: str = ""            # 그래프가 그린 비교 구간의 이름
    전국선: list[dict] = field(default_factory=list)  # 같은 조건 전국 중앙값
    도시: dict | None = None      # 같은 조건에서 가장 싼 도시 / 비싼 도시
    단계추적: list[단계판정] = field(default_factory=list)
    해석: str = ""
    확인사항: list[str] = field(default_factory=list)
    모르는것: list[str] = field(default_factory=list)
    확인필요: bool = False        # HITL — 멈추지 않고 표시만 한다


# ── 기준가와 순위 ────────────────────────────────────────────────────
# 비교 단위를 이루는 열. 🔴 하나라도 빠지면 서로 다른 것을 한 분포에 섞는다.
#
# 실제로 `vrty`(품종)와 `sgg`(시군구)를 빠뜨려 틀렸다. 복숭아 한 품목의
# 2025년 7월 응답이 53행이었는데, 그것은 「백도 상품」이 여러 지역에서
# 조사된 것이었다. 이를 한 덩어리로 보면 **지역 간 가격차가 연도 간
# 변동으로 둔갑한다.**
비교키 = ("item_nm", "se_nm", "vrty_nm", "grd_nm", "sgg_nm")


def 같은달_관측(월별행: list[dict], 대상월: str) -> dict[tuple, dict]:
    """**같은 것끼리** 같은 달 관측을 연도와 함께 모은다.

    같은 달끼리만 비교하는 이유 — 농산물은 계절성이 지배적이라 7월 값을
    1월 값과 비교하면 계절을 이상으로 잘못 읽는다.

    같은 지역·같은 품종·같은 등급끼리만 비교하는 이유 — 그러지 않으면
    「서울이 광주보다 비싸다」가 「올해가 작년보다 비싸다」로 읽힌다.
    """
    버킷: dict[tuple, dict] = {}
    for 행 in 월별행:
        조사연월 = 행.get("exmn_ym", "")
        if len(조사연월) != 6 or 조사연월[4:] != 대상월:
            continue
        try:
            평균가 = float(행.get("pmm_avgprc") or 0)
        except (TypeError, ValueError):
            continue
        if 평균가 <= 0:
            continue
        키 = tuple(행.get(열) for 열 in 비교키)
        칸 = 버킷.setdefault(키, {"관측": [], "단위": ""})
        칸["관측"].append((조사연월[:4], 평균가))
        단위 = (행.get("unit") or "").strip()
        크기 = (행.get("unit_sz") or "").strip()
        if 단위 and not 칸["단위"]:
            칸["단위"] = f"{크기}{단위}" if 크기 and 크기 != "1" else 단위
    return 버킷


# 🔴 **단위는 단계마다 다르다.** perDay 는 「10kg 상자」·「1단」·「1개」처럼
#    규격 단위의 가격이고, 산지·도매 정산은 총액÷총물량이라 원/kg 이다.
#    단위를 떼고 나란히 놓으면 3,637 → 53,382 → 1,033 처럼 아무 의미 없는
#    나열이 된다. 실제로 그렇게 만들어 놓고 「사슬」이라고 불렀다.
#
# 🔴 처음에는 이것을 모듈 전역 `단위기억` 으로 옮겼다가 **결정성을 깼다.**
#    `같은달_관측()` 이 채우고 `품목별_집계()` 가 몰래 읽는 구조라, 같은 입력이
#    호출 순서에 따라 `""` 가 되기도 `"10kg"` 가 되기도 했다.
#    이제 **단위를 버킷 안에 함께 담는다** — 함수는 인자 밖을 보지 않는다.


def 품목별_집계(버킷: dict[tuple, dict], 올해: str,
             최소관측수: int) -> tuple[dict[str, dict], dict]:
    """비교 단위별 순위를 **품목 하나로 모은다.**

    🔑 한 품목은 지역·품종·등급별로 수십 개의 비교 단위를 갖는다. 그중
    **몇 개에서 올해가 가장 비싼가**를 세는 것이 이 함수의 일이다.

        "전국 28개 비교 구간 중 21곳에서 지난 5년 7월 중 가장 비쌉니다"

    임계치를 고르지 않고도 「얼마나 이상한가」를 말할 수 있다. 한 지역만
    튀는 것과 전국이 함께 튀는 것이 자연히 갈린다.

    🔴 **버린 구간을 세어 함께 돌려준다.** `최소관측수` 는 우리가 고른
       수다. 고르지 않을 수는 없다 — 과거 관측이 2개뿐인데 순위를 매기면
       「2년 중 1번째」가 되어 **말이 관측보다 커진다.** 그러나 말없이
       버리면 그 자체가 숨긴 임계치다. 우리는 「임의 임계치를 쓰지
       않는다」고 적어 두었으므로, 이 수만큼은 **몇 개를 왜 뺐는지**
       산출물에 드러내야 그 말이 참이 된다.
    """
    집계: dict[str, dict] = {}
    버림 = {"올해관측없음": 0, "과거관측부족": 0}
    for 키, 칸 in sorted(버킷.items(), key=lambda kv: tuple(
            "" if v is None else str(v) for v in kv[0])):
        관측 = 칸["관측"]
        품목 = 키[0]
        올해값 = [v for y, v in 관측 if y == 올해]
        과거값 = [v for y, v in 관측 if y != 올해]
        if not 올해값:
            버림["올해관측없음"] += 1
            continue
        if len(과거값) < 최소관측수:
            버림["과거관측부족"] += 1
            continue
        현재 = statistics.mean(올해값)
        순위, 전체, 배수 = 순위판정(현재, 과거값)

        d = 집계.setdefault(품목, {
            "구간수": 0, "최고순위구간": 0, "상위10퍼센트구간": 0,
            "배수들": [], "대표": None, "구간": [],
        })
        d["구간수"] += 1
        d["배수들"].append(배수)
        if 순위 == 1:
            d["최고순위구간"] += 1
        if 순위 / 전체 <= 0.1:
            d["상위10퍼센트구간"] += 1
        구간 = {
            "구분": 키[1], "품종": 키[2], "등급": 키[3], "지역": 키[4],
            "올해": round(현재), "평년평균": round(statistics.mean(과거값)),
            "배수": round(배수, 2), "순위": f"{순위}/{전체}",
            "단위": 칸["단위"],
        }
        d["구간"].append(구간)
        if 순위 == 1:
            d.setdefault("최고목록", []).append(구간)

    for 품목, d in 집계.items():
        # 동점이면 이름으로 가른다 — 그러지 않으면 실행마다 순서가 달라진다
        d["구간"].sort(key=lambda x: (-x["배수"], x["지역"], x["품종"],
                                   x["등급"], x["구분"]))
        # 🔴 「149개 구간 중 19개」는 사용자에게 아무 의미가 없다.
        #    조달 담당자는 「구간」이 아니라 **도시**로 생각한다.
        #    그래서 순위의 기준 단위를 도시로 바꾼다 —
        #    「그 도시에서 파는 것 중 하나라도 5년 내 최고면 그 도시를 센다」
        도시전체 = {c["지역"] for c in d["구간"] if c["지역"] != "온라인"}
        도시최고 = {c["지역"] for c in (d.get("최고목록") or [])
                 if c["지역"] != "온라인"}
        d["도시수"] = len(도시전체)
        d["최고도시수"] = len(도시최고)
        d["최고도시비율"] = round(len(도시최고) / len(도시전체), 3) if 도시전체 else 0
        # 🔴 대표를 「배수 최대」로 뽑으면 안 된다. 719개 구간에서 극단값 하나를
        # 골라 「가장 비싸다」고 말하는 셈이라 전체를 오도한다. 실제로 그렇게
        # 만들었더니 다섯 품목이 전부 「5년 내 최고가」로 나왔다.
        # **중앙값 구간**을 대표로 삼는다 — 절반은 이보다 높고 절반은 낮다.
        d["대표"] = d["구간"][len(d["구간"]) // 2]
        d["최고구간"] = d["구간"][0]          # 참고용으로만 남긴다
        d["중앙배수"] = round(statistics.median(d["배수들"]), 2)
        d["최고비율"] = round(d["최고순위구간"] / d["구간수"], 3)
        del d["배수들"]
    return 집계, 버림


def 순위판정(올해값: float, 과거: list[float]) -> tuple[int, int, float]:
    """올해 값이 과거를 포함한 전체에서 몇 번째로 높은지.

    반환: (순위, 전체개수, 평년평균 대비 배수)
    """
    더높은것 = sum(1 for v in 과거 if v > 올해값)
    return 더높은것 + 1, len(과거) + 1, 올해값 / statistics.mean(과거)


# ── 사람 말로 옮기기 ─────────────────────────────────────────────────
def 조사(말: str, 받침있을때: str, 받침없을때: str) -> str:
    """한국어 조사를 앞 글자의 받침에 맞춰 고른다.

    이걸 안 하면 「청양고추·꽈리고추 등가」·「중품)으로」 같은 문장이 나온다.
    산출물을 사람이 읽는 물건으로 만들려면 이 정도는 맞춰야 한다.
    괄호·공백으로 끝나면 그 앞의 글자를 본다.
    """
    글자 = next((c for c in reversed(말) if c not in "()[] "), "")
    if not ("가" <= 글자 <= "힣"):
        return 받침있을때                    # 숫자·영문은 받침 있는 쪽으로 둔다
    return 받침없을때 if (ord(글자) - 0xAC00) % 28 == 0 else 받침있을때


def 사람말로(집계: dict, 대상월: str, 기준연수: int) -> str:
    """🔴 통계 용어를 쓰지 않는다.

    사용자는 구매 담당자이지 통계 전공자가 아니다. 「표준편차 2.3배」는
    행동으로 이어지지 않지만 「전국 대부분에서 5년 내 최고」는 이어진다.

    🔴 그리고 **한 구간의 순위를 품목 전체의 결론처럼 말하지 않는다.**
    한 품목은 지역·품종·등급별로 수십 개 구간을 갖는다. 그중 하나가 최고가인
    것과 대부분이 최고가인 것은 전혀 다른 상황이다. 그래서 **몇 곳에서
    그런가**를 문장의 주어로 쓴다.
    """
    # 🔴 의사결정자는 숫자에 반응한다. 「평소의 2.1배」보다 「2,400원 → 5,040원」
    #    이 먼저 와야 한다. 배수는 그 뒤에 괄호로 붙인다.
    #    그리고 「149가지 경우」처럼 우리 내부 용어를 쓰지 않는다 —
    #    실제로 「가게 149곳인가 산지 149곳인가」라는 질문을 받았다.
    달 = f"{int(대상월)}월"
    최고 = 집계["최고도시수"]
    중앙 = 집계["중앙배수"]
    목록 = 집계.get("최고목록") or []
    전체지역 = 집계["도시수"]
    대표 = 집계["대표"]

    # 🔴 카드 머리에 증감률이 있고 바로 아래에 추이 그래프가 있다.
    #    같은 것을 문장으로 또 쓰면 세 번 말하는 셈이다. 그래서 이 문장은
    #    **그림이 말하지 못하는 것**만 담는다 — 어디에서, 무엇이 최고인가.
    if 최고 == 0:
        방향 = "높습니다" if 중앙 >= 1.0 else "낮습니다"
        return (f"시세를 조사하는 전국 {전체지역}개 도시 어디에서도 "
                f"최근 {기준연수}년 {달} 최고가는 아닙니다. 전반적으로 {방향}.")

    # 🔴 「조사 지역 23곳」이라고만 쓰면 그 23이 무엇인지 알 수 없다.
    #    실제로는 농산물유통정보가 매일 시세를 조사하는 **전국 25개 도시**다
    #    (서울·부산·대구… + 온라인 채널). 그래서 **도시 이름을 직접 쓴다.**
    # 🔴 점수 하나로만 정렬하면 동점 순서가 해시 시드에 좌우된다.
    #    PYTHONHASHSEED 를 바꾸자 「후지·쓰가루」가 「쓰가루·후지」로 바뀌었다.
    #    이름을 보조 키로 둬야 실행마다 같은 문장이 나온다.
    도시들 = sorted({c["지역"] for c in 목록 if c["지역"] != "온라인"},
                 key=lambda v: (-max(c["배수"] for c in 목록 if c["지역"] == v), v))
    품종들 = sorted({c["품종"] for c in 목록},
                 key=lambda v: (-sum(1 for c in 목록 if c["품종"] == v), v))
    으뜸 = max(목록, key=lambda c: (c["배수"], c["지역"], c["품종"], c["등급"]))
    품종말 = "·".join(품종들[:2]) + (" 등" if len(품종들) > 2 else "")
    도시말 = "·".join(도시들[:3])
    꼬리 = f" 등 {len(도시들)}개 도시" if len(도시들) > 3 else ""

    보기 = "·".join(도시들[:3]) + ("…" if len(도시들) > 3 else "")
    가운데 = (f"시세를 조사하는 전국 {전체지역}개 도시 가운데 "
           f"{len(도시들)}곳({보기})에서 최근 {기준연수}년 {달} 중 가장 비쌉니다.")
    묶음 = f" 오른 품종은 {품종말}입니다." if len(품종들) > 1 else ""
    return 가운데 + 묶음


def 도시비교(집계: dict, 기준: dict) -> dict | None:
    """같은 품종·등급·판매형태 안에서 **오늘 가장 싼 도시와 가장 비싼 도시**.

    🔑 사용자가 실제로 하려는 일은 「사는 것」이다. 「어디가 많이 올랐나」만
    알려주면 그다음 행동이 없다. **같은 물건을 어디서 더 싸게 살 수 있나**가
    붙어야 판단이 행동으로 이어진다.

    🔴 비교는 **같은 품종·같은 등급·같은 판매형태 안에서만** 한다.
       상품과 중품, 후지와 아오리를 섞어 「여기가 싸다」고 하면 거짓이 된다.

    🔴 그리고 이것은 **점포가 아니라 도시**다. 우리가 가진 것은 도시별
       조사가격이지 특정 판매처의 가격이 아니다. 배송비·거래조건도 모른다.
    """
    같은것 = [c for c in 집계["구간"]
            if c["구분"] == 기준["구분"] and c["품종"] == 기준["품종"]
            and c["등급"] == 기준["등급"] and c["지역"] != "온라인"]
    if len(같은것) < 2:
        return None
    싼곳 = min(같은것, key=lambda c: c["올해"])
    비싼곳 = max(같은것, key=lambda c: c["올해"])
    if 싼곳["지역"] == 비싼곳["지역"]:
        return None
    차이 = 비싼곳["올해"] - 싼곳["올해"]
    return {
        "조건": f"{기준['품종']} {기준['등급']} · {기준['구분']}",
        "도시수": len(같은것),
        "싼곳": {"지역": 싼곳["지역"], "값": 싼곳["올해"]},
        "비싼곳": {"지역": 비싼곳["지역"], "값": 비싼곳["올해"]},
        "차이": 차이,
        "차이율": round(차이 / 싼곳["올해"] * 100),
    }


def 전국중앙(집계: dict, 기준: dict) -> dict | None:
    """그래프에 함께 그릴 **전국 중앙값**. 한 구간만 보면 기준이 없다.

    같은 품종·등급·판매형태의 모든 도시를 연도별로 모아 중앙값을 낸다.
    「전국은 이런데 이 구간은 이렇다」가 한 그림에서 읽혀야 한다.
    """
    return {"조건": f"{기준['품종']} {기준['등급']} · {기준['구분']}"}


def 최고지점(집계: dict) -> dict | None:
    """가장 크게 오른 한 곳. **문장이 아니라 값으로 넘긴다.**

    문장에 섞어두면 다른 정보에 묻힌다. 화면에서 별도 자리를 갖는 편이
    「그래서 어디를 봐야 하나」에 바로 답한다.
    """
    목록 = 집계.get("최고목록") or []
    if not 목록:
        return None
    c = max(목록, key=lambda x: (x["배수"], x["지역"], x["품종"], x["등급"]))
    율 = round((c["올해"] / c["평년평균"] - 1) * 100)
    return {"지역": c["지역"], "품종": c["품종"], "등급": c["등급"],
            "평년": c["평년평균"], "올해": c["올해"],
            "증감": f"{'+' if 율 >= 0 else ''}{율}%"}


# 🔴 「비교불가」와 「평년수준」은 다른 말이다.
#
# 실제로 이것을 섞어 사고가 났다. 산지에 과거 자료가 없어 판정을 못 한 것을
# 「산지는 평년 수준」이라고 출력했고, 그 결과 다섯 품목 전부에서 근거 없는
# 결론(「소매 단계에서 벌어진다」)이 나왔다. **모르는 것을 안다고 말한 것이다.**
비교불가 = "비교불가"


def 자리표현(순위표기: str | None) -> str:
    """**순위 축.** 과거 관측 중 몇 번째인지만 말한다. 임계치 없음."""
    if not 순위표기:
        return 비교불가
    try:
        순위, 전체 = (int(v) for v in 순위표기.split("/"))
    except (ValueError, AttributeError):
        return 비교불가
    if 순위 == 1:
        return f"{전체}년 중 가장 높음"
    if 순위 == 전체:
        return f"{전체}년 중 가장 낮음"
    return f"{전체}년 중 {순위}번째"


def 대비표현(올해: float | None, 평년평균: float | None) -> str:
    """**평균 축.** 평년평균 대비 부호만 본다. 임계치 없음 — 부호는 데이터가 정한다.

    🔴 순위와 평균 대비는 **다른 축**이다. 과거가 {100,200,300,400,500}이고
       올해가 350이면 순위는 3/6(하위권)이지만 평균(300)보다 **높다.**
       둘 다 사실인데 하나로 뭉치려다 「+5%인데 평년보다 낮다」가 나왔다.
    """
    if 올해 is None or not 평년평균:
        return 비교불가
    if 올해 > 평년평균:
        return "평년보다 높음"
    if 올해 < 평년평균:
        return "평년보다 낮음"
    return "평년 수준"


def 관측표현(순위표기: str | None) -> str:
    """단계별 판정을 한 단어로. **원인을 말하지 않는다.**

    🔴 **임계치를 쓰지 않는다.** 처음에는 「배수 1.15 넘으면 높음」으로
       만들었는데, 그 1.15 는 내가 고른 값이다. 「임의 임계치가 하나도
       없다」고 말해온 원칙을 라벨에서 스스로 어긴 것이었다.

       고치는 재료는 이미 있었다 — 각 단계의 **순위**를 계산해 놓고 쓰지
       않고 있었다. 6개 관측 중 1번째면 「가장 높음」이다. 이건 우리가
       정한 것이 아니라 센 것이다.
    """
    if not 순위표기:
        return 비교불가
    try:
        순위, 전체 = (int(v) for v in 순위표기.split("/"))
    except (ValueError, AttributeError):
        return 비교불가
    if 순위 == 1:
        return "가장 높음"
    if 순위 == 전체:
        return "가장 낮음"
    if 순위 <= 전체 / 2:
        return "높은 편"
    return "낮은 편"


def 단계해석(단계들: list[단계판정]) -> str:
    """어느 단계에서 이탈이 **처음 관측되는가**.

    🔴 두 가지를 지킨다.
      ① 판정할 수 없는 단계는 **결론에 넣지 않는다.** 「비교불가」를
         「평년수준」처럼 쓰지 않는다.
      ② 원인을 단정하지 않는다. 「산지가 원인이다」가 아니라
         「산지에서 이미 관측된다」까지만 말한다 — 선행성을 측정하지 않았다.
    """
    # 🔴 **`대비` 만 읽는다.** 「어디서 벌어졌나」는 평균 대비 이야기다.
    #    순위(`자리`)를 여기서 쓰면 「하위권」을 「평년보다 낮다」로 잘못 옮긴다.
    판정됨 = [d for d in 단계들 if d.대비 not in (비교불가, "", "자료없음")]
    미판정 = [d.단계 for d in 단계들 if d.대비 in (비교불가, "", "자료없음")]
    꼬리 = (f" (단, {'·'.join(미판정)} 단계는 비교할 과거 자료가 없어 판정에서 뺐습니다.)"
          if 미판정 else "")

    if not 판정됨:
        return "유통 단계별로 비교할 과거 자료가 없어 어디서 벌어진 일인지 확인하지 못했습니다."

    높은단계 = [d for d in 판정됨 if d.대비 == "평년보다 높음"]
    if not 높은단계:
        낮은단계 = [d.단계 for d in 판정됨 if d.대비 == "평년보다 낮음"]
        if 낮은단계:
            return (f"유통 단계로 보면 **{'·'.join(낮은단계)}가 평년보다 낮습니다.** "
                    f"일부 지역·등급에서만 높게 나온 것입니다.{꼬리}")
        return (f"유통 단계로 보면 **전 단계가 평년 수준**입니다. "
                f"일부 지역·등급에서만 높게 나온 것입니다.{꼬리}")

    if len(판정됨) == 1:
        return (f"**{판정됨[0].단계} 단계에서 높게 관측됩니다.** "
                f"다른 단계와 비교하지 못해 어디서 시작됐는지는 알 수 없습니다.{꼬리}")

    if 높은단계[0].단계 == 판정됨[0].단계:
        if len(높은단계) == len(판정됨):
            # 🔴 「거래처를 바꿔도 달라지지 않는다」는 공개 가격만으로
            #    뒷받침되지 않는다. 단정하지 않고 확인 항목으로 낮춘다.
            return (f"**가장 앞선 {판정됨[0].단계} 단계에서 이미 높습니다.** "
                    f"아래 단계도 모두 높습니다.{꼬리}")
        return f"**가장 앞선 {판정됨[0].단계} 단계에서 이미 높게 관측됩니다.**{꼬리}"

    # 🔴 앞 단계를 「평년 수준」이라고 못박으면 안 된다. 실제로 산지가 -40%
    #    인데 「평년 수준」이라고 말하고 있었다. **그 단계의 실제 판정을 쓴다.**
    앞 = 판정됨[0]
    뒤 = 높은단계[0]
    앞말 = {"평년보다 낮음": "평년보다 낮은데",
          "평년 수준": "평년 수준인데",
          "평년보다 높음": "평년보다 높지만"}[앞.대비]
    return (f"**{앞.단계}는 {앞말} {뒤.단계} 단계에서 더 벌어집니다.** "
            f"다른 시장·법인의 가격을 확인해 볼 가치가 있습니다.{꼬리}")


