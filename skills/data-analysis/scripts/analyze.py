def 오늘한줄(판정들: list[품목판정]) -> str:
    """🔴 **이상한 게 없으면 없다고 말한다.**

    상위 N개를 항상 채우면 「오늘 먼저 볼 것」이라는 제목 자체가 거짓이 된다.
    평소와 다른 품목이 없는 날에는 그렇게 말하고, 목록은 참고로만 남긴다.
    이 제품의 약속은 「매일 5개」가 아니라 「오늘 이상한 것」이다.
    """
    if not 판정들:
        return "평소와 다르게 움직인 품목이 없습니다."
    강함 = [p for p in 판정들 if p.확인필요]
    if 강함:
        이름 = "·".join(p.품목 for p in 강함[:3])
        꼬리 = "" if len(강함) <= 3 else " 등"
        말 = 이름 + 꼬리
        return (f"{말}{조사(말, '이', '가')} **조사한 모든 도시에서** "
                f"최근 5년 같은 달 최고가입니다.")
    오름 = [p for p in 판정들 if p.배수 >= 1.0]
    if not 오름:
        return ("**오늘은 평소와 크게 다른 품목이 없습니다.** "
                "아래는 그중 상대적으로 높은 순서일 뿐입니다.")
    return f"**{len(오름)}개 품목**이 평소 이맘때보다 높습니다."


def 공통항목_빼내기(판정들: list[품목판정]) -> list[str]:
    """🔴 **모든 카드에 똑같이 나오는 문장은 카드에서 뺀다.**

    「귀사의 계약단가를 모릅니다」가 다섯 카드에 다섯 번 적히면 분량만 늘고
    정작 그 카드에만 해당하는 내용이 묻힌다. 전부에 걸리는 것은 **아래에서
    한 번** 말하고, 카드에는 **그 품목에만 해당하는 것**만 남긴다.
    """
    if len(판정들) < 2:
        return []

    def 집합(p: 품목판정) -> set[str]:
        return set(p.확인사항) | set(p.모르는것)

    공통 = 집합(판정들[0])
    for p in 판정들[1:]:
        공통 &= 집합(p)
    if not 공통:
        return []

    for p in 판정들:
        p.확인사항 = [v for v in p.확인사항 if v not in 공통]
        p.모르는것 = [v for v in p.모르는것 if v not in 공통]
    return sorted(공통)


