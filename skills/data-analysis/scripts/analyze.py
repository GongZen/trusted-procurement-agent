"""수집한 원본에서 「오늘 먼저 볼 것」을 골라 판정 JSON을 만든다.

**이 파일이 숫자에 대한 유일한 권한을 가진다.** 렌더러(HTML 카드·텍스트 보고)는
여기서 나온 JSON만 읽고 계산하지 않는다. LLM도 마찬가지다 —
Solar 는 문장을 다듬을 뿐 숫자를 만들거나 바꾸지 못한다(Scaffolding S2).

판정 방법 — **임의 임계치를 쓰지 않는다**

    기준가   같은 품목·같은 구분·같은 등급·**같은 달**의 과거 N년 월평균
    이상도   올해 값이 그 관측들 사이에서 **몇 번째로 높은가**
    순위     이상도가 큰 순

    「1.5배 넘으면 이상」 같은 우리가 고른 선이 없다. 비교 대상은 전부
    API 가 준 과거 관측이고, 판정은 그 관측들 사이의 **순위**다.
    이것이 Step 4 통과 기준(「임의 임계치가 하나도 없음」)을 만족시키는 방법이다.
"""
from __future__ import annotations

import json
import statistics
from dataclasses import dataclass, field, asdict
from datetime import datetime, timezone, timedelta

SCHEMA_VERSION = "1.0"
KST = timezone(timedelta(hours=9))


# ── 판정 결과 ────────────────────────────────────────────────────────
@dataclass
class 단계판정:
    """유통 한 단계에서 관측된 것. 원인이 아니라 **관측**이다."""
    단계: str                    # 산지 · 도매 · 소매
    올해: float | None
    평년평균: float | None
    배수: float | None
    순위: str | None             # "1/6" — 과거 포함 몇 개 중 몇 번째
    관측: str                    # 높음 · 평년수준 · 낮음 · 자료없음


@dataclass
class 품목판정:
    순위: int
    품목: str
    구분: str                    # 소매 · 중도매
    등급: str
    올해: float
    평년평균: float
    배수: float
    순위표기: str                # "1/6"
    사람말: str                  # 통계 용어를 쓰지 않은 한 문장
    단계추적: list[단계판정] = field(default_factory=list)
    해석: str = ""
    확인사항: list[str] = field(default_factory=list)
    모르는것: list[str] = field(default_factory=list)
    확인필요: bool = False        # HITL — 멈추지 않고 표시만 한다


# ── 기준가와 순위 ────────────────────────────────────────────────────
# 비교 단위를 이루는 열. 🔴 하나라도 빠지면 서로 다른 것을 한 분포에 섞는다.
#
# 실제로 `vrty`(품종)와 `sgg`(시군구)를 빠뜨려 틀렸다. 복숭아 한 품목의
# 2025년 7월 응답이 53행이었는데, 그것은 「백도 상품」이 여러 지역에서
# 조사된 것이었다. 이를 한 덩어리로 보면 **지역 간 가격차가 연도 간
# 변동으로 둔갑한다.**
비교키 = ("item_nm", "se_nm", "vrty_nm", "grd_nm", "sgg_nm")


def 같은달_관측(월별행: list[dict], 대상월: str) -> dict[tuple, list[tuple[str, float]]]:
    """**같은 것끼리** 같은 달 관측을 연도와 함께 모은다.

    같은 달끼리만 비교하는 이유 — 농산물은 계절성이 지배적이라 7월 값을
    1월 값과 비교하면 계절을 이상으로 잘못 읽는다.

    같은 지역·같은 품종·같은 등급끼리만 비교하는 이유 — 그러지 않으면
    「서울이 광주보다 비싸다」가 「올해가 작년보다 비싸다」로 읽힌다.
    """
    버킷: dict[tuple, list[tuple[str, float]]] = {}
    for 행 in 월별행:
        조사연월 = 행.get("exmn_ym", "")
        if len(조사연월) != 6 or 조사연월[4:] != 대상월:
            continue
        try:
            평균가 = float(행.get("pmm_avgprc") or 0)
        except (TypeError, ValueError):
            continue
        if 평균가 <= 0:
            continue
        키 = tuple(행.get(열) for 열 in 비교키)
        버킷.setdefault(키, []).append((조사연월[:4], 평균가))
    return 버킷


def 품목별_집계(버킷: dict[tuple, list[tuple[str, float]]], 올해: str,
             최소관측수: int) -> dict[str, dict]:
    """비교 단위별 순위를 **품목 하나로 모은다.**

    🔑 한 품목은 지역·품종·등급별로 수십 개의 비교 단위를 갖는다. 그중
    **몇 개에서 올해가 가장 비싼가**를 세는 것이 이 함수의 일이다.

        "전국 28개 비교 구간 중 21곳에서 지난 5년 7월 중 가장 비쌉니다"

    임계치를 고르지 않고도 「얼마나 이상한가」를 말할 수 있다. 한 지역만
    튀는 것과 전국이 함께 튀는 것이 자연히 갈린다.
    """
    집계: dict[str, dict] = {}
    for 키, 관측 in 버킷.items():
        품목 = 키[0]
        올해값 = [v for y, v in 관측 if y == 올해]
        과거값 = [v for y, v in 관측 if y != 올해]
        if not 올해값 or len(과거값) < 최소관측수:
            continue
        현재 = statistics.mean(올해값)
        순위, 전체, 배수 = 순위판정(현재, 과거값)

        d = 집계.setdefault(품목, {
            "구간수": 0, "최고순위구간": 0, "상위10퍼센트구간": 0,
            "배수들": [], "대표": None, "구간": [],
        })
        d["구간수"] += 1
        d["배수들"].append(배수)
        if 순위 == 1:
            d["최고순위구간"] += 1
        if 순위 / 전체 <= 0.1:
            d["상위10퍼센트구간"] += 1
        d["구간"].append({
            "구분": 키[1], "품종": 키[2], "등급": 키[3], "지역": 키[4],
            "올해": round(현재), "평년평균": round(statistics.mean(과거값)),
            "배수": round(배수, 2), "순위": f"{순위}/{전체}",
        })

    for 품목, d in 집계.items():
        d["구간"].sort(key=lambda x: -x["배수"])
        # 🔴 대표를 「배수 최대」로 뽑으면 안 된다. 719개 구간에서 극단값 하나를
        # 골라 「가장 비싸다」고 말하는 셈이라 전체를 오도한다. 실제로 그렇게
        # 만들었더니 다섯 품목이 전부 「5년 내 최고가」로 나왔다.
        # **중앙값 구간**을 대표로 삼는다 — 절반은 이보다 높고 절반은 낮다.
        d["대표"] = d["구간"][len(d["구간"]) // 2]
        d["최고구간"] = d["구간"][0]          # 참고용으로만 남긴다
        d["중앙배수"] = round(statistics.median(d["배수들"]), 2)
        d["최고비율"] = round(d["최고순위구간"] / d["구간수"], 3)
        del d["배수들"]
    return 집계


def 순위판정(올해값: float, 과거: list[float]) -> tuple[int, int, float]:
    """올해 값이 과거를 포함한 전체에서 몇 번째로 높은지.

    반환: (순위, 전체개수, 평년평균 대비 배수)
    """
    더높은것 = sum(1 for v in 과거 if v > 올해값)
    return 더높은것 + 1, len(과거) + 1, 올해값 / statistics.mean(과거)


# ── 사람 말로 옮기기 ─────────────────────────────────────────────────
def 사람말로(집계: dict, 대상월: str, 기준연수: int) -> str:
    """🔴 통계 용어를 쓰지 않는다.

    사용자는 구매 담당자이지 통계 전공자가 아니다. 「표준편차 2.3배」는
    행동으로 이어지지 않지만 「전국 대부분에서 5년 내 최고」는 이어진다.

    🔴 그리고 **한 구간의 순위를 품목 전체의 결론처럼 말하지 않는다.**
    한 품목은 지역·품종·등급별로 수십 개 구간을 갖는다. 그중 하나가 최고가인
    것과 대부분이 최고가인 것은 전혀 다른 상황이다. 그래서 **몇 곳에서
    그런가**를 문장의 주어로 쓴다.
    """
    달 = f"{int(대상월)}월"
    구간수 = 집계["구간수"]
    최고 = 집계["최고순위구간"]
    중앙 = 집계["중앙배수"]

    if 최고 == 구간수:
        return (f"조사한 **{구간수}개 지역·등급 전부**에서 "
                f"지난 {기준연수}년 {달} 중 **올해가 가장 비쌉니다.**")
    if 최고 >= 구간수 / 2:
        return (f"조사한 {구간수}곳 중 **{최고}곳**에서 지난 {기준연수}년 {달} 중 "
                f"**가장 비쌉니다.** 절반이 넘습니다.")
    if 최고 > 0:
        return (f"조사한 {구간수}곳 중 **{최고}곳**에서 지난 {기준연수}년 {달} 중 "
                f"가장 비쌉니다. 전반적으로는 평소 이맘때의 **{중앙}배** 수준입니다.")

    if 중앙 >= 1.0:
        return (f"평소 이맘때보다 **{round((중앙 - 1) * 100)}% 높습니다.** "
                f"({구간수}곳 중앙값)")
    return (f"평소 이맘때보다 {round((1 - 중앙) * 100)}% 낮습니다. "
            f"({구간수}곳 중앙값)")


# 🔴 「비교불가」와 「평년수준」은 다른 말이다.
#
# 실제로 이것을 섞어 사고가 났다. 산지에 과거 자료가 없어 판정을 못 한 것을
# 「산지는 평년 수준」이라고 출력했고, 그 결과 다섯 품목 전부에서 근거 없는
# 결론(「소매 단계에서 벌어진다」)이 나왔다. **모르는 것을 안다고 말한 것이다.**
비교불가 = "비교불가"


def 관측표현(배수: float | None) -> str:
    """단계별 판정을 한 단어로. **원인을 말하지 않는다.**

    배수가 없다는 것은 「평년과 같다」가 아니라 **「비교할 과거가 없다」**이다.
    """
    if 배수 is None:
        return 비교불가
    if 배수 >= 1.15:
        return "높음"
    if 배수 <= 0.85:
        return "낮음"
    return "평년수준"


def 단계해석(단계들: list[단계판정]) -> str:
    """어느 단계에서 이탈이 **처음 관측되는가**.

    🔴 두 가지를 지킨다.
      ① 판정할 수 없는 단계는 **결론에 넣지 않는다.** 「비교불가」를
         「평년수준」처럼 쓰지 않는다.
      ② 원인을 단정하지 않는다. 「산지가 원인이다」가 아니라
         「산지에서 이미 관측된다」까지만 말한다 — 선행성을 측정하지 않았다.
    """
    판정됨 = [d for d in 단계들 if d.관측 not in (비교불가, "자료없음")]
    미판정 = [d.단계 for d in 단계들 if d.관측 in (비교불가, "자료없음")]
    꼬리 = (f" (단, {'·'.join(미판정)} 단계는 비교할 과거 자료가 없어 판정에서 뺐습니다.)"
          if 미판정 else "")

    if not 판정됨:
        return "유통 단계별로 비교할 과거 자료가 없어 어디서 벌어진 일인지 확인하지 못했습니다."

    높은단계 = [d for d in 판정됨 if d.관측 == "높음"]
    if not 높은단계:
        낮은단계 = [d.단계 for d in 판정됨 if d.관측 == "낮음"]
        if 낮은단계:
            return (f"유통 단계로 보면 **{'·'.join(낮은단계)}가 평년보다 낮습니다.** "
                    f"일부 지역·등급에서만 높게 나온 것입니다.{꼬리}")
        return (f"유통 단계로 보면 **전 단계가 평년 수준**입니다. "
                f"일부 지역·등급에서만 높게 나온 것입니다.{꼬리}")

    if len(판정됨) == 1:
        return (f"**{판정됨[0].단계} 단계에서 높게 관측됩니다.** "
                f"다른 단계와 비교하지 못해 어디서 시작됐는지는 알 수 없습니다.{꼬리}")

    if 높은단계[0].단계 == 판정됨[0].단계:
        if len(높은단계) == len(판정됨):
            return (f"**가장 앞선 {판정됨[0].단계} 단계에서 이미 높습니다.** "
                    f"아래 단계도 모두 높습니다. 거래처를 바꾸는 것으로는 "
                    f"달라지기 어려운 종류입니다.{꼬리}")
        return f"**가장 앞선 {판정됨[0].단계} 단계에서 이미 높게 관측됩니다.**{꼬리}"

    앞 = 판정됨[0].단계
    뒤 = 높은단계[0].단계
    return (f"**{앞}는 평년 수준인데 {뒤} 단계에서 벌어집니다.** "
            f"다른 시장·법인의 가격을 확인해 볼 가치가 있습니다.{꼬리}")


# ── 산출물 조립 ──────────────────────────────────────────────────────
def 오늘한줄(판정들: list[품목판정]) -> str:
    """🔴 **이상한 게 없으면 없다고 말한다.**

    상위 N개를 항상 채우면 「오늘 먼저 볼 것」이라는 제목 자체가 거짓이 된다.
    평소와 다른 품목이 없는 날에는 그렇게 말하고, 목록은 참고로만 남긴다.
    이 제품의 약속은 「매일 5개」가 아니라 「오늘 이상한 것」이다.
    """
    if not 판정들:
        return "평소와 다르게 움직인 품목이 없습니다."
    강함 = [p for p in 판정들 if p.확인필요]
    if 강함:
        return (f"**{len(강함)}개 품목**이 조사 지역 절반 넘는 곳에서 "
                f"최근 최고가입니다.")
    오름 = [p for p in 판정들 if p.배수 >= 1.0]
    if not 오름:
        return ("**오늘은 평소와 크게 다른 품목이 없습니다.** "
                "아래는 그중 상대적으로 높은 순서일 뿐입니다.")
    return f"**{len(오름)}개 품목**이 평소 이맘때보다 높습니다."


def 보고서만들기(판정들: list[품목판정], 설정: dict,
              수집기록: dict, 검증기록: dict, 기준일: str) -> dict:
    """렌더러가 읽을 **유일한** 산출물. 여기 없는 숫자는 화면에 못 나온다."""
    return {
        "schema_version": SCHEMA_VERSION,
        "생성시각": datetime.now(KST).isoformat(timespec="seconds"),
        "기준일": 기준일,
        "오늘한줄": 오늘한줄(판정들),
        "설정":설정,
        "수집": 수집기록,
        "검증": 검증기록,
        "우선검토": [asdict(p) for p in 판정들],
        "미판정": {
            "2층_매입가": "입력 없음 — 사용자 매입가가 없어 판정하지 않았습니다",
        },
        "한계": [
            "귀사의 계약단가·재고·발주 일정을 모릅니다. 계약이 걸려 있으면 이 변동과 무관할 수 있습니다.",
            "앞으로 오를지 내릴지 예측하지 않습니다. 선행성을 측정하지 않았기 때문입니다.",
            "유통 단계별 관측은 원인 규명이 아닙니다. 어디서 벌어졌는지까지만 말합니다.",
        ],
    }


def 저장(보고서: dict, 경로) -> None:
    with open(경로, "w", encoding="utf-8") as fp:
        json.dump(보고서, fp, ensure_ascii=False, indent=2)
